<?php

declare(strict_types=1);

namespace Mridul\Payments;

use PDO;

/**
 * The order, as the payment code is allowed to touch it.
 *
 * This deliberately exposes four operations and no general query method. The
 * payment handler has no business reading customers or writing prices, and a
 * class that cannot express those things cannot be talked into them by a
 * clever request.
 *
 * Confirming and failing are not written here as UPDATE statements. They call
 * `confirm_online_payment` and `fail_online_payment`, the SECURITY DEFINER
 * functions in migration 0017, because those already hold the rules that
 * matter — the amount must agree with the order total, an order that has moved
 * on is left alone, stock goes back when a payment is abandoned. Reimplementing
 * that here in PHP would mean two versions of the same rules, and the day they
 * disagree is the day somebody is charged wrongly.
 *
 * The database user in ORDERS_DB_USER therefore needs exactly:
 *
 *   grant execute on function public.confirm_online_payment(
 *     uuid, text, text, bigint, text, text, text) to mridul_payments;
 *   grant execute on function public.fail_online_payment(uuid, text)
 *     to mridul_payments;
 *   grant select on public.orders to mridul_payments;
 *
 * and nothing else. Not the service role, not the table owner.
 */
final class Orders
{
    private PDO $db;

    public function __construct(Config $config)
    {
        $this->db = new PDO(
            $config->dsn,
            $config->dbUser,
            $config->dbPassword,
            [
                PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                // Real prepared statements, so a parameter can never be parsed
                // as SQL no matter what arrives in it.
                PDO::ATTR_EMULATE_PREPARES   => false,
            ],
        );
    }

    /**
     * An order number is generated by the database as MR-YYYY-NNNNNN. Anything
     * else is not worth a round trip, and checking the shape here keeps a
     * hostile value away from the query in the first place.
     */
    public static function looksLikeOrderNumber(string $value): bool
    {
        return preg_match('/^MR-[0-9]{4}-[0-9]{6}$/', $value) === 1;
    }

    /**
     * @return array{id:string,order_number:string,status:string,total_paise:int}|null
     */
    public function findByNumber(string $orderNumber): ?array
    {
        if (!self::looksLikeOrderNumber($orderNumber)) {
            return null;
        }

        $statement = $this->db->prepare(
            'select id, order_number, status, total_paise
               from public.orders
              where order_number = :number
              limit 1'
        );
        $statement->execute(['number' => $orderNumber]);
        $row = $statement->fetch();

        if ($row === false) {
            return null;
        }

        return [
            'id'           => (string) $row['id'],
            'order_number' => (string) $row['order_number'],
            'status'       => (string) $row['status'],
            'total_paise'  => (int) $row['total_paise'],
        ];
    }

    /**
     * Confirm, having already verified with CCAvenue directly.
     *
     * `$amountPaise` is what the GATEWAY said was paid, passed in so the
     * database can refuse if it disagrees with the order. Do not "helpfully"
     * pass the order total here: that would make the check compare a number
     * with itself and pass every time.
     */
    public function confirm(
        string $orderId,
        int $amountPaise,
        ?string $paymentId,
        ?string $reference,
        ?string $method,
    ): void {
        $statement = $this->db->prepare(
            'select public.confirm_online_payment(
                       :order_id::uuid, :provider, :payment_id,
                       :amount, :reference, :method, null)'
        );
        $statement->execute([
            'order_id'   => $orderId,
            'provider'   => 'ccavenue',
            'payment_id' => $paymentId,
            'amount'     => $amountPaise,
            'reference'  => $reference,
            'method'     => $method,
        ]);
    }

    /** Release a payment that was declined, cancelled or abandoned. */
    public function fail(string $orderId, ?string $reason): void
    {
        $statement = $this->db->prepare(
            'select public.fail_online_payment(:order_id::uuid, :reason)'
        );
        $statement->execute([
            'order_id' => $orderId,
            'reason'   => $reason,
        ]);
    }
}
